// Package hwid отвечает за учёт устройств клиента и решение, пускать ли
// конкретное устройство к подписке.
//
// У прослойки нет собственного полноценного реестра устройств: панель
// Remnawave умеет считать устройства сама (через Devices), и именно её
// данные Enforce использует для лимита. Поверх этого MultiGate добавляет
// только то, чего нет у панели, - блокировку конкретного устройства через
// overrides.
package hwid

import (
	"context"
	"fmt"
	"log/slog"

	"github.com/qwe8nxtroud/multigate/internal/model"
	"github.com/qwe8nxtroud/multigate/internal/store"
)

// SyntheticSource - значение model.Client.HWIDSource, когда HWID не пришёл
// от клиента напрямую (например, заголовком), а выведен эвристикой из
// User-Agent.
const SyntheticSource = "ua"

// IsSyntheticHWID сообщает, можно ли доверять HWID клиента как настоящему
// идентификатору устройства панели.
//
// Синтетический HWID (собранный из User-Agent) годится, чтобы локально
// заблокировать устройство в MultiGate: он стабилен для одного и того же
// клиента и достаточно уникален. Но он НЕ совпадает с тем, что панель
// хранит у себя в реестре HWID. Поэтому удалять по такому идентификатору
// устройство через Devices.DeleteDevice нельзя: в лучшем случае панель не
// найдёт такую запись, в худшем - по случайному совпадению будет удалено
// чужое устройство с похожим User-Agent. Вызывающая сторона обязана
// проверять эту функцию перед любым вызовом DeleteDevice.
func IsSyntheticHWID(c model.Client) bool {
	return c.HWIDSource == SyntheticSource
}

// Devices - доступ к реестру устройств пользователя на стороне панели.
// Реализуется пакетом remnawave. Используется и административными
// сценариями (просмотр и ручное удаление устройства пользователя), и
// самим Enforce - лимит устройств считается по этим данным, а не по
// локальному журналу запросов (тот наполняется HWID из заголовка клиента
// без всякой проверки, и его легко исчерпать чужими значениями).
type Devices interface {
	Devices(ctx context.Context, userRef string) ([]model.Device, error)
	DeleteDevice(ctx context.Context, userRef, hwid string) error
}

// Enforce решает, можно ли отдать подписку клиенту c для пользователя u.
//
// Проверяются по порядку:
//  1. включён ли режим (store.KeyHWIDEnforce), иначе разрешаем сразу;
//  2. нет ли локальной блокировки этого устройства или пользователя целиком
//     (store.Override с action="block");
//  3. не превышает ли устройство лимит PanelUser.HWIDDeviceLimit - по
//     данным реестра устройств панели (devices.Devices), а не по журналу
//     запросов.
//
// devices - источник устройств (реализация пакета remnawave). Может быть
// nil - тогда лимит проверить не на чем, и Enforce пропускает клиента,
// как и при любой другой невозможности посчитать устройства.
//
// Раньше "уже известное" устройство определялось по локальному журналу
// запросов (request_log): HWID туда пишется из заголовка клиента x-hwid
// без всякой проверки, поэтому лимит было легко обойти или, наоборот,
// исчерпать чужой, просто перебирая случайные значения этого заголовка на
// чужой ссылке подписки - настоящее устройство владельца получало бы отказ.
// Реестр панели куда безопаснее: туда попадают устройства, которые
// подтвердила сама панель, а не то, что клиент сказал о себе прослойке.
//
// log используется только для одного: если поход в панель за списком
// устройств не удался, это тихо не должно резать доступ клиенту (сбой
// связи - не повод отключать платящего пользователя), но и молчать об
// этом не годится - потерянный лимит устройств лучше видеть в журнале
// процесса. log==nil допустим, тогда предупреждение просто не пишется.
func Enforce(ctx context.Context, db *store.DB, devices Devices, log *slog.Logger, c model.Client, u model.PanelUser) (allowed bool, reason string) {
	if !db.GetBool(ctx, store.KeyHWIDEnforce) {
		return true, ""
	}

	// Локальная блокировка: сначала конкретное устройство у этого
	// пользователя, затем устройство целиком, затем пользователь целиком.
	// Это ровно то, что делает store.FindOverride.
	if o, ok := db.FindOverride(ctx, u.ShortUUID, c.HWID); ok && o.Action == "block" {
		if o.Reason != "" {
			return false, "устройство заблокировано: " + o.Reason
		}
		return false, "устройство заблокировано"
	}

	if c.HWID == "" {
		// Не смогли определить устройство ни из заголовка, ни из UA.
		// Проверять лимит не на чем: лучше пропустить, чем заблокировать
		// легитимного клиента из-за того, что не смогли его опознать.
		return true, ""
	}

	limit := u.HWIDDeviceLimit
	if limit <= 0 {
		// Панель не прислала ограничение - считаем, что лимита нет.
		return true, ""
	}

	if IsSyntheticHWID(c) {
		// Синтетический HWID - локальная эвристика MultiGate по User-Agent,
		// в реестре панели его нет и быть не может (клиент никогда не
		// отправлял такую строку панели как настоящий hwid). Сверять его с
		// devices бессмысленно: устройство всегда будет выглядеть "новым",
		// даже если это тот же самый клиент, что и минуту назад. Точной
		// проверки лимита для таких клиентов у прослойки нет, и лучше
		// пропустить, чем отключать платящего клиента по недостоверному
		// признаку.
		return true, ""
	}

	if devices == nil {
		return true, ""
	}

	devs, err := devices.Devices(ctx, u.Ref)
	if err != nil {
		if log != nil {
			log.Warn("hwid: не проверить лимит устройств, панель недоступна",
				"short_uuid", u.ShortUUID, "err", err)
		}
		return true, ""
	}
	for _, d := range devs {
		if d.HWID == c.HWID {
			// Устройство уже зарегистрировано в панели - лимит не пересчитываем.
			return true, ""
		}
	}
	if len(devs) >= limit {
		return false, fmt.Sprintf("превышен лимит устройств: %d/%d", len(devs), limit)
	}
	return true, ""
}
