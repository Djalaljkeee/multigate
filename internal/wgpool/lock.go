package wgpool

import "sync"

// keyLock: мьютексы по ключу (пул плюс пользователь плюс устройство).
//
// Клиент дёргает подписку по таймеру, и Lease для одной и той же пары
// пользователь-устройство может быть вызван почти одновременно из двух
// горутин обработки запроса. keyLock сериализует их внутри процесса, чтобы
// проверка "уже есть выдача" и выдача нового конфига не гонялись друг
// с другом. От выдачи одного и того же свободного конфига двум разным
// устройствам защищает не это, а транзакция с блокировкой строки в БД
// (см. acquireFree в db.go).
type keyLock struct {
	m sync.Map // string -> *sync.Mutex
}

// lock захватывает мьютекс по ключу и возвращает функцию освобождения.
func (k *keyLock) lock(key string) func() {
	v, _ := k.m.LoadOrStore(key, &sync.Mutex{})
	mu := v.(*sync.Mutex)
	mu.Lock()
	return mu.Unlock
}
