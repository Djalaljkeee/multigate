package grace

import "sync"

// keyLock: мьютексы по ключу (короткий идентификатор пользователя).
//
// Подписка опрашивается клиентом каждые несколько часов, и Maybe для одного
// и того же пользователя вполне может быть вызван дважды почти одновременно
// (ретрай HTTP-клиента, два воркера обработки запроса). keyLock сериализует
// такие вызовы внутри одного процесса, чтобы не запускать заявку и восстановление
// параллельно. Это дополнение к проверке в базе, а не замена ей: между
// несколькими процессами прослойки keyLock не защищает, это делает атомарная
// запись в grace_users (см. tryClaim).
type keyLock struct {
	m sync.Map // string -> *sync.Mutex
}

// lock захватывает мьютекс по ключу и возвращает функцию освобождения.
func (k *keyLock) lock(key string) func() {
	v, _ := k.m.LoadOrStore(key, &sync.Mutex{})
	mu := v.(*sync.Mutex)
	mu.Lock()
	return mu.Unlock
}
