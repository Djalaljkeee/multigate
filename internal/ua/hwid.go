package ua

import (
	"crypto/sha256"
	"encoding/hex"
	"strings"

	"github.com/qwe8nxtroud/multigate/internal/model"
)

// syntheticHWID собирает стабильный идентификатор устройства из того, что
// удалось узнать про клиента, когда он сам не прислал HWID в заголовках
// (так ведёт себя большинство десктопных клиентов и v2rayNG/Clash на
// мобильных). Это НЕ настоящий HWID из панели, только приближение для
// мягкого учёта устройств, но оно обязано быть стабильным между запросами
// одного и того же устройства.
//
// Идентификатор специально не завязан на имя приложения: одно и то же
// физическое устройство должно давать один и тот же синтетический
// идентификатор вне зависимости от того, каким клиентом подписки на нём
// пользуются в моменте. Иначе один телефон с двумя установленными
// приложениями посчитался бы как два разных устройства.
//
// Обратная сторона: два разных физических устройства одной модели на одной
// версии ОС дадут одинаковый идентификатор. Без собственного HWID от
// клиента отличить их нечем, это принятый компромисс мягкого учёта,
// не жёсткий лимит.
func syntheticHWID(c model.Client) (string, bool) {
	device := strings.ToLower(strings.TrimSpace(c.Device))
	osVersion := strings.ToLower(strings.TrimSpace(c.OSVersion))
	// Без модели устройства и версии ОС сигнала слишком мало: платформ
	// всего пять, и по одной платформе не отличить одно устройство от другого.
	if device == "" || osVersion == "" {
		return "", false
	}

	h := sha256.New()
	h.Write([]byte(string(c.Platform)))
	h.Write([]byte{0})
	h.Write([]byte(osVersion))
	h.Write([]byte{0})
	h.Write([]byte(device))
	sum := h.Sum(nil)
	// Префикс "ua-" сразу маркирует происхождение при взгляде на значение
	// глазами (в логах, в админке), не полагаясь только на HWIDSource.
	// 32 символа hex (128 бит) с запасом достаточно, чтобы не бояться коллизий.
	return "ua-" + hex.EncodeToString(sum)[:32], true
}
